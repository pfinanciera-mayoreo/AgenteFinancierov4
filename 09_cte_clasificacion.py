def cte_catalogo_expandido() -> str:
    """
    Igual que en la v2/v3: SELECT DISTINCT (deduplica), expande la
    plantilla 'venezuela' a las 4 empresas venezolanas, descarta 'olo', y
    remapea '07.Publicidad' -> '06.Gastos Varios' (confirmado con el
    usuario: esa subclasificación fue eliminada).
    """
    empresas_venezuela = ["Febeca", "Beval", "Prisma", "Sillaca"]

    def remap(col):
        return f"CASE WHEN {col} = '07.Publicidad' THEN '06.Gastos Varios' ELSE {col} END"

    ramas = [f"""
    SELECT DISTINCT cuenta, Empresa,
           {remap('Subclasificacion')} AS Subclasificacion,
           {remap('"Subclasificacion 2"')} AS Subclasificacion_2,
           Clasificacion, nombre_cuenta
    FROM catalogo_gyp
    WHERE Empresa NOT IN ('venezuela', 'olo')"""]

    for empresa in empresas_venezuela:
        ramas.append(f"""
    SELECT DISTINCT cuenta, '{empresa}' AS Empresa,
           {remap('Subclasificacion')} AS Subclasificacion,
           {remap('"Subclasificacion 2"')} AS Subclasificacion_2,
           Clasificacion, nombre_cuenta
    FROM catalogo_gyp WHERE Empresa = 'venezuela'""")

    return "catalogo_expandido AS (" + "\n    UNION ALL".join(ramas) + "\n)"


def cte_mayor_gyp_clasificado() -> str:
    """
    Devuelve el WITH completo listo para anteponer a cualquier consulta.
    Combina mayor_contable + asientos_planificacion (Origen_Datos: 'ERP' o
    'Planificación') y aplica el mapeo REAL de cada empresa (extraído de
    sus archivos gyp.xlsx reales) como fuente principal de clasificación,
    con el catálogo genérico como respaldo si una cuenta no aparece en el
    mapeo real de su empresa.
    """
    empresas_con_mapeo = ["Cofersa", "Prisma", "Mundial", "Febeca", "Sillaca", "Beval"]
    mapeos_sql = {
        "Cofersa": MAPEO_REAL_COFERSA_SQL, "Prisma": MAPEO_REAL_PRISMA_SQL,
        "Mundial": MAPEO_REAL_MUNDIAL_SQL, "Febeca": MAPEO_REAL_FEBECA_SQL,
        "Sillaca": MAPEO_REAL_SILLACA_SQL, "Beval": MAPEO_REAL_BEVAL_SQL,
    }

    tablas_mapeo = ",\n".join(
        f"""mapeo_{empresa.lower()} (cuenta, categoria) AS (
    VALUES
{mapeos_sql[empresa]}
)"""
        for empresa in empresas_con_mapeo
    )

    def _condicion_empresa(empresa):
        # "Prisma CR" son movimientos de Cofersa (CC 4-07-00) reclasificados
        # a otra entidad — pero usan el MISMO catálogo de cuentas de
        # Cofersa, así que el mapeo real de Cofersa también debe aplicarles.
        if empresa == "Cofersa":
            return "m.Empresa IN ('Cofersa', 'Prisma CR')"
        return f"m.Empresa = '{empresa}'"

